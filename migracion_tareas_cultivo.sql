-- Agenda de trabajo ligada a lotes de cultivo y operadores existentes.
CREATE TABLE IF NOT EXISTS tareas_cultivo (
    id INT NOT NULL AUTO_INCREMENT,
    lote_id INT NOT NULL,
    titulo VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500) DEFAULT NULL,
    categoria ENUM('Riego','Nutrición','Poda','Trasplante','Control sanitario','Seguimiento','Cosecha','Otro') NOT NULL DEFAULT 'Seguimiento',
    fecha_programada DATE NOT NULL,
    estado ENUM('Pendiente','En curso','Completada','Cancelada') NOT NULL DEFAULT 'Pendiente',
    prioridad ENUM('Baja','Media','Alta') NOT NULL DEFAULT 'Media',
    responsable_id INT DEFAULT NULL,
    completada_en DATETIME DEFAULT NULL,
    created_by INT NOT NULL,
    updated_by INT DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_tareas_fecha_estado (fecha_programada, estado),
    KEY idx_tareas_lote (lote_id),
    KEY idx_tareas_responsable (responsable_id),
    CONSTRAINT fk_tareas_lote FOREIGN KEY (lote_id) REFERENCES lotes_cultivo (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_tareas_responsable FOREIGN KEY (responsable_id) REFERENCES operadores (id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_tareas_created_by FOREIGN KEY (created_by) REFERENCES operadores (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_tareas_updated_by FOREIGN KEY (updated_by) REFERENCES operadores (id) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
